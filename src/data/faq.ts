/** 공백을 지우고 소문자로 바꿔, '보호막가동'처럼 띄어쓰기 없이 쳐도 찾을 수 있게 한다 */
export function normalizeFaqQuery(text: string): string {
  return text.toLowerCase().replace(/\s+/g, '')
}

export interface FaqMatch {
  section: FaqSection
  item: FaqItem
}

/** 질문을 먼저, 답변에만 나오는 문항을 그 뒤에 둔다 */
export function searchFaq(query: string): FaqMatch[] {
  const q = normalizeFaqQuery(query)
  if (!q) return []
  const inQuestion: FaqMatch[] = []
  const inAnswer: FaqMatch[] = []
  for (const section of FAQ_SECTIONS) {
    for (const item of section.items) {
      if (normalizeFaqQuery(item.q).includes(q)) inQuestion.push({ section, item })
      else if (normalizeFaqQuery(item.a).includes(q)) inAnswer.push({ section, item })
    }
  }
  return [...inQuestion, ...inAnswer]
}
